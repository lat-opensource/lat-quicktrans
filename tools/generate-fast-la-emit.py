import argparse
import json
from pathlib import Path

from fast_la_reference import parse_bit_fields


FAST_LA_REG_OPERANDS = (
    "gpr_", "fpr_", "fcc_", "scr_", "opd_fcsr", "opd_csr", "opd_opcache"
)
PSEUDOINSTRUCTION_NOFUNCTION = (
    "accl", "align", "code", "far_jump", "data_li", "data_add", "inst_diff",
    "data_st", "data_st_rel_table", "profile", "pcaddi_relocate",
    "jump_epilogue", "indirect_goto", "ret_indirect_goto",
    "jcc_direct_exit", "pseudo_end",
)
PSEUDOINSTRUCTIONS = (
    "label", "x86_inst", "mov64", "mov32_sx", "mov32_zx", "add", "sub",
    "addi_addrx", "load_addrx", "store_addrx", "ill", "nop",
) + PSEUDOINSTRUCTION_NOFUNCTION


def fast_la_name(name):
    return "FT_LA_" + name.replace(".", "_").upper()


def fast_la_opcode_name(name):
    return "FT_LA_OPCODE_" + name.replace(".", "_").upper()


def operand_bits(opnd, fields):
    return sum(end - start + 1 for start, end in fields[opnd])


def operand_check(opnd, fields):
    bits = operand_bits(opnd, fields)

    if opnd.startswith(FAST_LA_REG_OPERANDS):
        return (
            "    FT_LA_ASSERT(((uint32_t){} >> {}) == 0);\n".format(
                opnd, bits))
    if opnd.startswith("imm_si") or opnd.startswith("imm_off"):
        return "    FT_LA_ASSERT(ft_la_fits_simm({}, {}));\n".format(
            opnd, bits)
    if opnd.startswith("imm_"):
        return (
            "    FT_LA_ASSERT(((uint32_t){} >> {}) == 0);\n".format(
                opnd, bits))
    return ""


def encode_operand(opnd, fields):
    value = "(uint32_t){}".format(opnd)
    consumed = 0
    parts = []

    for start, end in fields[opnd]:
        bits = end - start + 1
        mask = (1 << bits) - 1
        source = value

        if consumed:
            source = "({} >> {})".format(value, consumed)

        piece = "(({} & 0x{:x}u) << {})".format(source, mask, start)
        if start == 0:
            piece = "({} & 0x{:x}u)".format(source, mask)
        parts.append(piece)
        consumed += bits

    return " | ".join(parts)


def emit_function(name, operands, fields):
    if name == "nop":
        return ""

    real_operands = [opnd for opnd in operands if opnd != "opd_invalid"]
    for opnd in real_operands:
        if opnd not in fields:
            raise ValueError("missing fast LA bit field for {}".format(opnd))

    function_name = fast_la_name(name)
    opcode_name = fast_la_opcode_name(name)
    parameters = ", ".join("int {}".format(opnd) for opnd in real_operands)
    arguments = ", ".join(real_operands)

    if not parameters:
        parameters = "void"
        emit_parameters = "uint32_t **code"
    else:
        emit_parameters = "uint32_t **code, " + parameters

    body = "static inline uint32_t {}({})\n{{\n".format(
        function_name, parameters)
    for opnd in real_operands:
        body += operand_check(opnd, fields)
    body += "    return {}".format(opcode_name)
    for opnd in real_operands:
        body += " |\n           {}".format(encode_operand(opnd, fields))
    body += ";\n}\n\n"
    body += "static inline void {}_EMIT({})\n{{\n".format(
        function_name, emit_parameters)
    body += "    ft_la_emit_u32(code, {}({}));\n".format(
        function_name, arguments)
    body += "}\n\n"
    return body


def generate_header(insts, fields):
    lines = [
        "/*\n",
        " * This file is generated by tools/generate-fast-la-emit.py.\n",
        " *\n",
        " * SPDX-FileCopyrightText: 2026 LATX Project Authors\n",
        " *\n",
        " * SPDX-License-Identifier: MIT\n",
        " */\n",
        "#ifndef QUICKTRANS_FAST_LA_EMIT_H\n",
        "#define QUICKTRANS_FAST_LA_EMIT_H\n\n",
        "#include <stdbool.h>\n",
        "#include <stdint.h>\n\n",
        "#if defined(CONFIG_LATX_DEBUG) && defined(CONFIG_TARGET)\n",
        "#include \"common.h\"\n",
        "#define FT_LA_ASSERT(cond) lsassert(cond)\n",
        "#else\n",
        "#define FT_LA_ASSERT(cond) ((void)0)\n",
        "#endif\n\n",
        "static inline bool ft_la_fits_simm(int value, int bits)\n",
        "{\n",
        "    int32_t min = -(1 << (bits - 1));\n",
        "    int32_t max = (1 << (bits - 1)) - 1;\n",
        "    return value >= min && value <= max;\n",
        "}\n\n",
        "static inline void ft_la_emit_u32(uint32_t **code, uint32_t insn)\n",
        "{\n",
        "#ifdef FT_LA_CHECK_SPACE\n",
        "    FT_LA_CHECK_SPACE(*code, sizeof(**code));\n",
        "#endif\n",
        "    **code = insn;\n",
        "    *code += 1;\n",
        "}\n\n",
        "enum {\n",
    ]

    for name, desc in insts.items():
        if name not in ("invalid", "ending"):
            lines.append("    {} = {},\n".format(
                fast_la_opcode_name(name), desc["opcode"]))
    lines.append("};\n\n")

    for name, desc in insts.items():
        if name not in ("invalid", "ending") and name not in PSEUDOINSTRUCTIONS:
            lines.append(emit_function(name, desc["opnd"], fields))

    lines.extend([
        "static inline uint32_t FT_LA_NOP(void)\n",
        "{\n",
        "    return FT_LA_ANDI(0, 0, 0);\n",
        "}\n\n",
        "static inline void FT_LA_NOP_EMIT(uint32_t **code)\n",
        "{\n",
        "    ft_la_emit_u32(code, FT_LA_NOP());\n",
        "}\n\n",
        "#undef FT_LA_ASSERT\n\n",
        "#endif\n",
    ])
    return "".join(lines)


def main():
    parser = argparse.ArgumentParser(
        description="Generate the Quicktrans fast LoongArch encoder header.")
    parser.add_argument("inst_template")
    parser.add_argument("ir2_assemble")
    parser.add_argument("output")
    args = parser.parse_args()

    insts = json.loads(Path(args.inst_template).read_text(encoding="utf-8"))
    fields = parse_bit_fields(args.ir2_assemble)
    output = Path(args.output)
    output.write_text(generate_header(insts, fields), encoding="utf-8")


if __name__ == "__main__":
    main()
