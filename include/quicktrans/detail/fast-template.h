static inline void ft_fields_refresh_modrm_cache(FastTemplateFields *fields)
{
    if (fields->modrm < 0) {
        fields->modrm_mod = 3;
        fields->modrm_reg = 7;
        fields->modrm_rm = 7;
    } else {
        fields->modrm_mod = (fields->modrm >> 6) & 3;
        fields->modrm_reg = (fields->modrm >> 3) & 7;
        fields->modrm_rm = fields->modrm & 7;
    }
    fields->modrm_reg_index = fields->modrm_reg |
                              (((fields->rex_bits >> 2) & 1) << 3);
    fields->modrm_rm_index = fields->modrm_rm |
                             ((fields->rex_bits & 1) << 3);
}

static inline void ft_fields_set_rex(FastTemplateFields *fields, int rex)
{
    fields->rex = rex;
    fields->rex_bits = rex >= 0 ? rex : 0;
    ft_fields_refresh_modrm_cache(fields);
}

static inline void ft_fields_set_modrm(FastTemplateFields *fields, int modrm)
{
    fields->modrm = modrm;
    ft_fields_refresh_modrm_cache(fields);
}

